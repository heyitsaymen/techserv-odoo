from collections import defaultdict

from odoo import Command, api, fields, models
from odoo.exceptions import AccessError, UserError, ValidationError

# États à partir desquels le technicien est « parti » : plus d'annulation ni de suppression
STARTED_STATES = ('in_progress', 'done', 'invoiced')


class MaintenanceRequest(models.Model):
    """Intervention chez un client.

    On étend ``maintenance.request`` qui fournit déjà : chatter et suivi des
    modifications, étapes en kanban, technicien (``user_id``), date planifiée
    (``schedule_date``), date de fin stockée (``schedule_end``), durée,
    priorité, calendrier et activités.
    """
    _inherit = 'maintenance.request'
    # La référence donnée au téléphone doit être cherchable comme le sujet
    _rec_names_search = ['reference', 'name']

    reference = fields.Char(
        string='Reference', readonly=True, copy=False, index=True, tracking=True,
        help="Unique reference given to the customer, generated by a sequence.")
    customer_id = fields.Many2one(
        'res.partner', string='Customer', tracking=True, index='btree_not_null',
        compute='_compute_customer_id', store=True, readonly=False, check_company=True)
    # Related stocké : permet de filtrer / grouper / écrire des règles d'accès
    # et des règles automatisées sur l'état sans dépendre du nom de l'étape.
    techserv_state = fields.Selection(
        related='stage_id.techserv_state', store=True, index=True, string='TechServ State')
    # Le technicien reste le champ standard ``user_id`` (res.users) : les règles
    # d'accès et les activités s'appuient dessus. Ses coordonnées viennent de sa
    # fiche employé (hr.employee.public : lisible par tous les utilisateurs internes),
    # rien n'est ressaisi sur l'intervention.
    technician_employee_id = fields.Many2one(
        'hr.employee.public', string='Technician Employee', compute='_compute_technician_employee_id')
    technician_phone = fields.Char(string='Technician Mobile', compute='_compute_technician_employee_id')
    # Lien avec la vente d'origine (création automatique à la confirmation du devis)
    sale_order_id = fields.Many2one(
        'sale.order', string='Sales Order', readonly=True, copy=False, index='btree_not_null',
        check_company=True, tracking=True)
    sale_line_id = fields.Many2one('sale.order.line', string='Sales Order Line', readonly=True, copy=False)
    # Facture standard (account.move) ; plusieurs interventions peuvent partager la même facture
    invoice_id = fields.Many2one(
        'account.move', string='Invoice', readonly=True, copy=False, index='btree_not_null',
        check_company=True, tracking=True)
    # Données de clôture (saisies par le technicien dans l'assistant de clôture)
    time_spent = fields.Float(string='Time Spent', tracking=True, help="Hours actually spent at the customer's.")
    part_ids = fields.One2many('techserv.intervention.part', 'intervention_id', string='Parts Used')
    picking_id = fields.Many2one(
        'stock.picking', string='Parts Delivery', readonly=True, copy=False, check_company=True)
    customer_signature = fields.Binary(string='Customer Signature', copy=False, attachment=True)
    signed_by = fields.Char(string='Signed By', copy=False, tracking=True)
    signed_on = fields.Datetime(string='Signed On', copy=False, tracking=True)
    # Champs standards dont on active le suivi (traçabilité « qui a changé quoi »)
    schedule_date = fields.Datetime(tracking=True)
    schedule_end = fields.Datetime(tracking=True)
    equipment_id = fields.Many2one(tracking=True)
    priority = fields.Selection(tracking=True)

    _reference_uniq = models.Constraint(
        'unique(reference)',
        "The intervention reference must be unique!",
    )

    @api.depends('reference', 'name')
    def _compute_display_name(self):
        for request in self:
            if request.reference:
                request.display_name = f"[{request.reference}] {request.name or ''}"
            else:
                request.display_name = request.name

    @api.depends('equipment_id')
    def _compute_customer_id(self):
        for request in self:
            if request.equipment_id.customer_id:
                request.customer_id = request.equipment_id.customer_id

    @api.depends('user_id', 'company_id')
    def _compute_technician_employee_id(self):
        for request in self:
            employee = self.env['hr.employee.public'].search([
                ('user_id', '=', request.user_id.id),
                ('company_id', '=', request.company_id.id),
            ], limit=1) if request.user_id else self.env['hr.employee.public']
            request.technician_employee_id = employee
            request.technician_phone = employee.mobile_phone or employee.work_phone

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            if not vals.get('reference'):
                vals['reference'] = self.env['ir.sequence'].next_by_code('techserv.intervention')
        return super().create(vals_list)

    def write(self, vals):
        # Les règles de changement d'étape sont contrôlées ici, côté serveur : elles
        # s'appliquent quel que soit le chemin (bouton, barre d'étapes cliquable,
        # glisser-déposer dans le kanban, import, appel RPC...).
        new_state = vals.get('stage_id') and self.env['maintenance.stage'].browse(vals['stage_id']).techserv_state
        if new_state == 'cancel':
            self._check_techserv_manager(self.env._("Only TechServ managers can cancel interventions."))
            self._check_can_be_cancelled()
        elif new_state == 'invoiced':
            self._check_techserv_manager(self.env._("Only TechServ managers can invoice interventions."))
        res = super().write(vals)
        if new_state == 'done' and self.filtered(lambda r: not r.customer_signature):
            raise UserError(self.env._(
                "An intervention can only be closed with the customer's signature: use the Close button."))
        if new_state == 'invoiced' and self.filtered(lambda r: not r.invoice_id):
            raise UserError(self.env._(
                "An intervention can only be marked as invoiced by the invoicing wizard."))
        return res

    # ------------------------------------------------------------------
    # Contraintes
    # ------------------------------------------------------------------

    @api.constrains('user_id', 'schedule_date', 'schedule_end', 'stage_id', 'archive')
    def _check_technician_overlap(self):
        """Un technicien ne peut pas être à deux endroits en même temps.

        Contrainte Python (et non SQL) : il faut comparer des intervalles de
        dates entre plusieurs lignes, ce qu'une contrainte UNIQUE ne sait pas faire.
        """
        for request in self:
            if (not request.user_id or not request.schedule_date or not request.schedule_end
                    or request.archive or request.techserv_state == 'cancel'):
                continue
            # sudo : la vérification doit voir toutes les interventions du
            # technicien, quelles que soient les règles d'accès de l'utilisateur courant
            overlapping = self.sudo().search([
                ('id', '!=', request.id),
                ('user_id', '=', request.user_id.id),
                ('schedule_date', '<', request.schedule_end),
                ('schedule_end', '>', request.schedule_date),
                ('techserv_state', '!=', 'cancel'),
                ('archive', '=', False),
            ], limit=1)
            if overlapping:
                raise ValidationError(self.env._(
                    "%(technician)s already has the intervention %(other)s at that time.",
                    technician=request.user_id.name, other=overlapping.display_name))

    @api.constrains('stage_id', 'user_id', 'schedule_date')
    def _check_planning_data(self):
        for request in self:
            if request.techserv_state in ('planned', 'in_progress') and not (request.user_id and request.schedule_date):
                raise ValidationError(self.env._(
                    "The intervention %s needs a technician and a scheduled date to be planned.",
                    request.display_name))

    def _check_can_be_cancelled(self):
        """On peut annuler tant que le technicien n'est pas parti (avant « En cours »)."""
        for request in self:
            if request.techserv_state in STARTED_STATES:
                raise UserError(self.env._(
                    "The intervention %s has already started: it can no longer be cancelled.",
                    request.display_name))

    def _check_techserv_manager(self, message):
        """Contrôle des droits côté serveur. Masquer un bouton ne suffit pas :
        une méthode publique peut être appelée par RPC ou depuis une autre vue."""
        if not (self.env.su or self.env.user.has_group('techserv_intervention.group_techserv_manager')):
            raise AccessError(message)

    @api.ondelete(at_uninstall=False)
    def _unlink_except_not_manager(self):
        # Doublé par une règle d'enregistrement globale (perm_unlink) pour les techniciens
        self._check_techserv_manager(self.env._("Only TechServ managers can delete interventions."))

    @api.ondelete(at_uninstall=False)
    def _unlink_except_started(self):
        """Interdit la suppression d'une intervention commencée (on garde une trace).

        ``at_uninstall=False`` : la règle ne s'applique pas à la désinstallation
        du module, qui doit pouvoir nettoyer ses données.
        """
        for request in self:
            if request.techserv_state in STARTED_STATES:
                raise UserError(self.env._(
                    "The intervention %s has already started: it cannot be deleted.",
                    request.display_name))

    # ------------------------------------------------------------------
    # Actions
    # ------------------------------------------------------------------

    def _get_techserv_stage(self, state):
        stage = self.env['maintenance.stage'].search([('techserv_state', '=', state)], limit=1)
        if not stage:
            raise UserError(self.env._("No stage is configured for the state '%s'.", state))
        return stage

    def _techserv_get_managers(self):
        """Responsables TechServ ayant accès à la société de l'intervention."""
        self.ensure_one()
        group = self.env.ref('techserv_intervention.group_techserv_manager')
        return group.sudo().all_user_ids.filtered(lambda u: not u.share and self.company_id in u.company_ids)

    def _techserv_notify_team(self, summary, note=None):
        """Prévient l'équipe technique dans Odoo : une activité « À faire » pour
        chaque membre de l'équipe de maintenance standard (maintenance.team), ou
        pour les responsables si l'équipe n'a pas de membre."""
        for request in self:
            users = request.maintenance_team_id.member_ids or request._techserv_get_managers()
            for user in users:
                request.activity_schedule(
                    'mail.mail_activity_data_todo', summary=summary, note=note, user_id=user.id)

    def _techserv_alert_urgent_unplanned(self):
        """Appelée par la règle automatisée « urgente non planifiée après 24 h » :
        une activité d'alerte pour chaque responsable de la société.
        Pas de doublon : on ne recrée pas l'activité si elle existe déjà."""
        activity_type = self.env.ref('techserv_intervention.mail_activity_type_urgent_unplanned')
        for request in self:
            if request.techserv_state != 'received' or request.priority != '3':
                continue
            already_alerted = request.activity_ids.filtered(
                lambda a: a.activity_type_id == activity_type).user_id
            for manager in request._techserv_get_managers() - already_alerted:
                request.activity_schedule(
                    activity_type_id=activity_type.id,
                    user_id=manager.id,
                    note=self.env._("Urgent request received on %s and still not planned.",
                                    fields.Datetime.to_string(request.create_date)),
                )

    def action_techserv_start(self):
        """Le technicien part chez le client : l'intervention passe « En cours »."""
        for request in self:
            if request.techserv_state != 'planned':
                raise UserError(self.env._("Only planned interventions can be started."))
        self.write({'stage_id': self._get_techserv_stage('in_progress').id})

    def action_techserv_cancel(self):
        self.write({
            'stage_id': self._get_techserv_stage('cancel').id,
            'archive': True,
            'recurring_maintenance': False,
        })

    def archive_equipment_request(self):
        # Le bouton standard « Annuler » applique désormais nos règles d'annulation
        return self.action_techserv_cancel()

    def reset_equipment_request(self):
        # Rouvrir une intervention annulée est réservé aux responsables
        self._check_techserv_manager(self.env._("Only TechServ managers can reopen interventions."))
        return super().reset_equipment_request()

    # ------------------------------------------------------------------
    # Clôture : sortie de stock des pièces
    # ------------------------------------------------------------------

    def _techserv_create_parts_picking(self):
        """Crée et valide le bon de sortie standard (stock.picking) des pièces.

        sudo() limité à ce bloc : le technicien n'est pas utilisateur de
        l'Inventaire, mais la sortie de stock est la conséquence normale de
        la clôture qu'il a le droit de faire.
        """
        self.ensure_one()
        parts = self.part_ids.filtered(lambda p: not p.move_id)
        if not parts:
            return self.env['stock.picking']
        warehouse = self.env['stock.warehouse'].sudo().search([('company_id', '=', self.company_id.id)], limit=1)
        if not warehouse:
            raise UserError(self.env._("No warehouse is configured for the company %s.", self.company_id.name))
        picking_type = warehouse.out_type_id
        source = picking_type.default_location_src_id
        destination = self.env.ref('stock.stock_location_customers')
        picking = self.env['stock.picking'].sudo().with_company(self.company_id).create({
            'picking_type_id': picking_type.id,
            'partner_id': self.customer_id.id,
            'origin': self.reference,
            'location_id': source.id,
            'location_dest_id': destination.id,
            'move_ids': [Command.create({
                'product_id': part.product_id.id,
                'product_uom_qty': part.quantity,
                'product_uom': part.product_id.uom_id.id,
                'location_id': source.id,
                'location_dest_id': destination.id,
            }) for part in parts],
        })
        picking.action_confirm()
        # Les pièces ont réellement été utilisées : quantité faite = quantité demandée
        for move in picking.move_ids:
            move.quantity = move.product_uom_qty
            move.picked = True
        result = picking.button_validate()
        if result is not True or picking.state != 'done':
            raise UserError(self.env._("The parts delivery %s could not be validated.", picking.name))
        for part, move in zip(parts, picking.move_ids):
            part.move_id = move
        self.picking_id = picking
        return picking

    # ------------------------------------------------------------------
    # Facturation
    # ------------------------------------------------------------------

    def _get_techserv_intervention_date(self):
        """Date de l'intervention : clôture, sinon date planifiée, sinon demande."""
        self.ensure_one()
        return self.close_date or (self.schedule_date and self.schedule_date.date()) or self.request_date

    def _is_under_warranty_on_intervention_date(self):
        self.ensure_one()
        return bool(self.equipment_id) and self.equipment_id._is_under_warranty_at(
            self._get_techserv_intervention_date())

    def _prepare_techserv_invoice_lines(self):
        """Lignes de facture d'une intervention : section, main-d'oeuvre (sauf
        garantie à la date de l'intervention), puis pièces (toujours facturées)."""
        self.ensure_one()
        equipment = self.equipment_id
        title = self.reference
        if equipment:
            title += f" - {equipment.name}" + (f" (S/N {equipment.serial_no})" if equipment.serial_no else "")
        lines = [Command.create({'display_type': 'line_section', 'name': title})]
        if self.time_spent:
            if self._is_under_warranty_on_intervention_date():
                lines.append(Command.create({
                    'display_type': 'line_note',
                    'name': self.env._("Labour covered by the warranty (until %s).", equipment.warranty_date),
                }))
            else:
                labour = self.env.ref('techserv_intervention.product_labour')
                lines.append(Command.create({
                    'product_id': labour.id,
                    'quantity': self.time_spent,
                    'product_uom_id': labour.uom_id.id,
                }))
        lines += [Command.create({
            'product_id': part.product_id.id,
            'quantity': part.quantity,
            'product_uom_id': part.product_uom_id.id,
        }) for part in self.part_ids]
        return lines

    def _techserv_create_invoices(self, grouping='customer'):
        """Crée les factures clients (account.move standard) des interventions
        terminées : une par intervention ou une par client (et par société)."""
        self._check_techserv_manager(self.env._("Only TechServ managers can invoice interventions."))
        wrong = self.filtered(lambda r: r.techserv_state != 'done' or r.invoice_id)
        if wrong:
            raise UserError(self.env._(
                "Only done interventions that are not invoiced yet can be invoiced: %s",
                ", ".join(wrong.mapped('display_name'))))
        without_customer = self.filtered(lambda r: not r.customer_id)
        if without_customer:
            raise UserError(self.env._(
                "These interventions have no customer: %s", ", ".join(without_customer.mapped('display_name'))))

        batches = defaultdict(lambda: self.browse())
        for intervention in self.sorted('id'):
            if grouping == 'intervention':
                key = intervention.id
            else:
                key = (intervention.company_id.id, intervention.customer_id.id)
            batches[key] |= intervention

        invoiced_stage = self._get_techserv_stage('invoiced')
        invoices = self.env['account.move']
        for batch in batches.values():
            invoice_lines = []
            for intervention in batch:
                invoice_lines += intervention._prepare_techserv_invoice_lines()
            invoice = self.env['account.move'].with_company(batch.company_id).create({
                'move_type': 'out_invoice',
                'partner_id': batch.customer_id.id,
                'company_id': batch.company_id.id,
                'invoice_origin': ", ".join(batch.mapped('reference')),
                'invoice_line_ids': invoice_lines,
            })
            batch.write({'invoice_id': invoice.id, 'stage_id': invoiced_stage.id})
            invoices |= invoice
        return invoices
